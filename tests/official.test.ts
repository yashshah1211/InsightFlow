import { existsSync, readFileSync } from 'node:fs';
import { beforeEach, afterEach, expect, it, vi } from 'vitest';
import { officialRepository } from '@/lib/db/official-repository';
import { assertOfficial, OFFICIAL_SHA256, OFFICIAL_ROWS_SHA256, officialRowsSha256 } from '@/lib/analysis/official';
import { parseFeedbackCsv, groupRecords, hashReview } from '@/lib/analysis/ingest';
import { createHash } from 'node:crypto';
import { DashboardResponse, FeedbackResponse, DataLabResponse } from '@/lib/contracts';
import { GET as dashboard } from '@/app/api/dashboard/route';
import { GET as feedback } from '@/app/api/feedback/route';
import { GET as lab } from '@/app/api/data-lab/route';
const req = (path:string) => new Request('http://localhost'+path);
beforeEach(() => vi.stubEnv('INSIGHTFLOW_DATA_MODE','official'));
afterEach(() => vi.unstubAllEnvs());
it.skipIf(!existsSync('data/raw/customer_feedback.csv'))('original CSV checksum and ALL competition invariants match', () => {
  const bytes=readFileSync('data/raw/customer_feedback.csv');
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(OFFICIAL_SHA256);
  const parsed=parseFeedbackCsv(bytes,{filename:'customer_feedback.csv',contentType:'text/csv'});
  const records=parsed.accepted.map((r,i)=>({kind:'record' as const,id:String(i),batchId:'official',...r,source:'official_csv' as const,normalizedHash:hashReview(r.rawText),importedAt:'2026-10-10T00:00:00Z',observedAt:null,annotation:null}));
  const patterns = groupRecords(records);
  expect(officialRowsSha256(records)).toBe(OFFICIAL_ROWS_SHA256);
  expect(assertOfficial(records,patterns,parsed.rejectedRows.length).recordCount).toBe(7000);
  expect(Math.max(...patterns.map(pattern => pattern.occurrenceCount))).toBe(295);
  expect(patterns.reduce((sum, pattern) => sum + pattern.occurrenceCount, 0)).toBe(7000);
});
it.skipIf(!existsSync('data/processed/official.json'))('real artifact serves frozen contracts with accurate provenance and dates', async () => {
  const response=await dashboard(req('/api/dashboard'));
  expect(response.status).toBe(200);
  const body=DashboardResponse.parse(await response.json());
  expect(body.meta.provenance.source).toBe('official_csv');
  expect(body.data.summary.recordCount).toBe(7000);
  expect(body.data.summary.timestampCoverage.covered).toBe(0);
  const page=FeedbackResponse.parse(await (await feedback(req('/api/feedback?view=patterns&page=2&pageSize=100'))).json());
  expect(page.meta.total).toBe(320);
  expect(page.data.items).toHaveLength(100);
  const labBody=DataLabResponse.parse(await (await lab(req('/api/data-lab'))).json());
  expect(labBody.data.officialDatasetAssertions).toBe('passed');
  expect(labBody.data.top20RecordCount).toBe(5025);
  expect(labBody.data.adaption.runs).toEqual([]);
  expect(await officialRepository.snapshot('unknown')).toBeNull();
});
